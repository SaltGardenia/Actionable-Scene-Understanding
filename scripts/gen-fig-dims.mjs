// Regenerates src/fig-dimensions.js with the intrinsic width/height of every
// PNG in public/figures, read from the IHDR chunk. Run after adding or
// replacing figures so PdfFigure can reserve the correct aspect ratio.
import fs from "node:fs";
import path from "node:path";

const dir = new URL("../public/figures", import.meta.url).pathname;
const out = {};
for (const f of fs.readdirSync(dir).filter((f) => f.endsWith(".png"))) {
  const b = fs.readFileSync(path.join(dir, f));
  out[f] = { w: b.readUInt32BE(16), h: b.readUInt32BE(20) };
}
const target = new URL("../src/fig-dimensions.js", import.meta.url).pathname;
fs.writeFileSync(
  target,
  "// generated by scripts/gen-fig-dims.mjs from PNG IHDR headers — rerun after changing figures\n" +
    "export const FIG_DIMS = " + JSON.stringify(out, null, 2) + ";\n"
);
console.log(`Wrote ${target} with ${Object.keys(out).length} figures`);
